-- Election Town: the race catalog, and race proposals that carry nothing but the race.
-- Apply after 20261009000003. A proposal is now just (race type, state, district, special):
-- the system derives the title, candidates, outcome basis, resolution wording, and "Other" remainder.

-- ---------------------------------------------------------------- catalog (identifiers only)

create table public.race_catalog (
  race_type text not null check (race_type in ('senate', 'governor', 'house')),
  state text not null,
  district text,                       -- house: '01'..'53', or 'AL' for at-large
  is_special boolean not null default false,
  polled boolean not null default false  -- PollingSource publishes an average (as of 2026-10-10)
);
create unique index race_catalog_unique on public.race_catalog (race_type, state, coalesce(district, ''), is_special);
alter table public.race_catalog enable row level security;
create policy catalog_read on public.race_catalog for select using (app.is_member());

